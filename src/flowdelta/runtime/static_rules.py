from pathlib import Path

RULE_ID = "flowdelta.n8n.agent-tool-write-without-ownership-check"
RULE_VERSION = "0.6.0"
RULE_PATH = Path("runtime/static-scan/rules/agent-tool-write-without-ownership-check.yaml")
WRITE_METHODS = ("DELETE", "PATCH", "PUT")


def rule_yaml() -> str:
    # The current static input contract has no authenticated requester/role binding.
    # A node name, fallback or admin variable cannot establish that trust boundary.
    # Keep model-influenced writes visible even when an owner comparison is present.
    methods = "|".join(WRITE_METHODS)
    lines = [
        "# Generated by flowdelta.runtime.static_rules. Do not edit by hand.",
        "rules:",
        f"  - id: {RULE_ID}",
        "    metadata:",
        f'      rule_version: "{RULE_VERSION}"',
        "      category: broken-access-control",
        '      cwe: "CWE-639: Authorization Bypass Through User-Controlled Key"',
        "      scope: >-",
        "        jsCode of an n8n toolCode node that an AI Agent can call through ai_tool,",
        "        extracted as one function per tool. Static condition only: it does not show",
        "        that the agent calls the tool or that a record changes.",
        "      meaning: >-",
        "        A model-influenced write target needs authorization review. The current",
        "        input contract cannot authenticate requester or role sources, so owner",
        "        comparisons and admin exceptions do not suppress this finding.",
        "    message: >-",
        "      Agent tool sends a write request whose target comes from model-written input.",
        "      Requester identity, role provenance and authorization must be verified separately;",
        "      a comparison or an admin variable name does not establish trusted authorization.",
        "    severity: WARNING",
        "    languages: [javascript]",
        "    taint:",
        "      sources:",
        "        - pattern: JSON.parse(query)",
        "        - pattern: query",
        "      sinks:",
        "        - all:",
        '            - inside: "helpers.httpRequest({..., method: $METHOD, ...})"',
        '            - inside: "helpers.httpRequest({..., url: $SINK, ...})"',
        "          where:",
        "            - metavariable: $METHOD",
        f"              regex: (?i)^['\"]?({methods})['\"]?$",
        "            - focus: $SINK",
    ]
    return "\n".join(lines) + "\n"
